export const POLICY = {
  humanRequest: /(人工|转接|真人|找客服|customer\s*service|human\s*(agent|support))/i,
  restricted: /(退款|退钱|赔偿|补偿|账号解封|解除封禁|开具?发票|诉讼|律师|法律纠纷|合同承诺|投诉)/i,
  orderStatus: /(订单|物流|快递|配送|发货|tracking|order)/i,
  injection: /(忽略.{0,8}(之前|上述|系统).{0,8}(指令|提示)|显示.{0,8}(系统提示|system prompt)|ignore.{0,12}(previous|system).{0,12}(instruction|prompt))/i
};

export function classifyMessage(message) {
  if (POLICY.humanRequest.test(message)) return { action: "handoff", reason: "explicit_request" };
  if (POLICY.restricted.test(message)) return { action: "handoff", reason: "restricted_business" };
  return { action: "answer", reason: POLICY.injection.test(message) ? "prompt_injection_attempt" : "normal" };
}

